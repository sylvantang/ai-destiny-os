describe('DaYun (大运)', () => {
  it('should calculate dayun sequence for 甲年 male (顺排)', () => {
    const birth: BirthInfo = {
      year: 1984,  // 甲子年
      month: 6,
      day: 15,
      hour: 12,
      minute: 0,
      longitude: 116.4,
      isDST: false,
      gender: '男',
    };

    const bazi = calcBaZi(birth);
    const dayun = calcDaYun(birth, bazi.month, bazi.year.stemIndex, bazi.day.stemIndex);

    expect(dayun.length).toBe(10);
    expect(dayun[0]!.startAge).toBeGreaterThan(0);
    expect(dayun[0]!.direction).toBe('顺排');

    // Each dayun should be 10 years apart
    for (let i = 1; i < dayun.length; i++) {
      const diff = dayun[i]!.startAge - dayun[i - 1]!.startAge;
      expect(diff).toBeCloseTo(10, 0);
    }
  });

  it('should calculate dayun sequence for 甲年 female (逆排)', () => {
    const birth: BirthInfo = {
      year: 1984,  // 甲子年
      month: 6,
      day: 15,
      hour: 12,
      minute: 0,
      longitude: 116.4,
      isDST: false,
      gender: '女',
    };

    const bazi = calcBaZi(birth);
    const dayun = calcDaYun(birth, bazi.month, bazi.year.stemIndex, bazi.day.stemIndex);

    expect(dayun[0]!.direction).toBe('逆排');
  });
});

