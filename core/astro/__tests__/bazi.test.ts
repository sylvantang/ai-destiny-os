describe('JieQi (节气)', () => {
  it('should calculate 24 solar terms', () => {
    const jieqi = getJieQi(2024);
    expect(jieqi.length).toBe(24);
  });

  it('should have 立春 around Feb 4', () => {
    const jieqi = getJieQi(2024);
    const lichun = jieqi.find(jq => jq.name === '立春');
    expect(lichun).toBeDefined();
    expect(lichun!.date.getUTCMonth()).toBe(1); // February (0-indexed)
    expect(lichun!.date.getUTCDate()).toBeGreaterThanOrEqual(3);
    expect(lichun!.date.getUTCDate()).toBeLessThanOrEqual(5);
  });

  it('should mark even indices as 节 and odd as 气', () => {
    const jieqi = getJieQi(2024);
    for (const jq of jieqi) {
      expect(jq.isJie).toBe(jq.index % 2 === 0);
    }
  });

  it('should have sequential longitudes', () => {
    const jieqi = getJieQi(2024).sort((a, b) => a.date.getTime() - b.date.getTime());
    for (let i = 1; i < jieqi.length; i++) {
      const prevLon = jieqi[i - 1]!.longitude;
      const currLon = jieqi[i]!.longitude;
      // After 冬至 (270°), next is 小寒 (285°), ..., up to 360/0
      const diff = (currLon - prevLon + 360) % 360;
      expect(diff).toBeCloseTo(15, 0);
    }
  });
});
